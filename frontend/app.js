// --- Metrics & Counters ---
function updateMetrics() {
  const total = state.hackathons.length;
  const online = state.hackathons.filter(h => h.mode === 'Online').length;
  const offline = state.hackathons.filter(h => h.mode === 'Offline' || h.mode === 'Hybrid').length;

  elements.totalCount.textContent = total;
  elements.onlineCount.textContent = online;
  elements.offlineCount.textContent = offline;
}

// --- Filter Engine ---
function applyFilters() {
  const { search, mode, city, tag, sort } = state.filters;
  const query = search.trim().toLowerCase();

  state.filtered = state.hackathons.filter(item => {
    // 1. Search Query Match
    if (query) {
      const matchTitle = (item.title || '').toLowerCase().includes(query);
      const matchOrg = (item.organizer || '').toLowerCase().includes(query);
      const matchVenue = (item.venue_address || '').toLowerCase().includes(query);
      const matchTags = (item.tags || []).some(t => t.toLowerCase().includes(query));
      if (!matchTitle && !matchOrg && !matchVenue && !matchTags) return false;
    }

    // 2. Mode Match
    if (mode !== 'ALL' && item.mode !== mode) {
      return false;
    }

    // 3. City Match
    if (city !== 'ALL') {
      if (city === 'Online' && item.mode !== 'Online') return false;
      if (city !== 'Online') {
        const itemCity = (item.city || '').toLowerCase();
        const itemVenue = (item.venue_address || '').toLowerCase();
        const targetCity = city.toLowerCase();
        if (!itemCity.includes(targetCity) && !itemVenue.includes(targetCity)) return false;
      }
    }

    // 4. Tag Match
    if (tag !== 'ALL') {
      const hasTag = (item.tags || []).some(t => t.toLowerCase().includes(tag.toLowerCase()));
      if (!hasTag) return false;
    }

    return true;
  });

  // Sorting
  state.filtered.sort((a, b) => {
    if (sort === 'deadline_asc') {
      return new Date(a.deadline || '2099-01-01') - new Date(b.deadline || '2099-01-01');
    } else if (sort === 'start_asc') {
      return new Date(a.start_date || '2099-01-01') - new Date(b.start_date || '2099-01-01');
    } else if (sort === 'title_asc') {
      return (a.title || '').localeCompare(b.title || '');
    }
    return 0;
  });

  elements.resultsCount.textContent = state.filtered.length;
  renderCards();
}

// --- Card Rendering ---
function renderCards() {
  const container = elements.cardsGrid;
  container.innerHTML = '';

  if (state.filtered.length === 0) {
    elements.emptyState.style.display = 'flex';
    return;
  }
  elements.emptyState.style.display = 'none';

  const now = new Date();

  state.filtered.forEach((h, index) => {
    const card = document.createElement('article');
    card.className = 'hackathon-card';
    card.style.animationDelay = `${index * 50}ms`;

    // Mode Badge Class & Icon
    let modeClass = 'badge-offline';
    let modeIcon = '📍 In-Person';
    let addressIcon = '🏛️';

    if (h.mode === 'Online') {
      modeClass = 'badge-online';
      modeIcon = '🌐 Online';
      addressIcon = '💻';
    } else if (h.mode === 'Hybrid') {
      modeClass = 'badge-hybrid';
      modeIcon = '🔀 Hybrid';
      addressIcon = '🌐/🏛️';
    }

    // Countdown calculation
    const deadlineDate = h.deadline ? new Date(h.deadline) : null;
    let countdownText = 'Open Registration';
    let isUrgent = false;

    if (deadlineDate && !isNaN(deadlineDate.getTime())) {
      const diffMs = deadlineDate - now;
      if (diffMs < 0) {
        countdownText = 'Registration Closed';
      } else {
        const days = Math.floor(diffMs / (1000 * 60 * 60 * 24));
        const hours = Math.floor((diffMs % (1000 * 60 * 60 * 24)) / (1000 * 60 * 60));
        if (days > 0) {
          countdownText = `${days}d ${hours}h left`;
          if (days <= 5) isUrgent = true;
        } else {
          countdownText = `${hours}h left!`;
          isUrgent = true;
        }
      }
    }

    // Tag Badges
    const tagsHtml = (h.tags || ['Tech', 'Hackathon'])
      .slice(0, 3)
      .map(t => `<span class="tag-badge">#${t}</span>`)
      .join('');

    card.innerHTML = `
      <div class="card-banner-wrapper">
        <img 
          src="${h.banner_url || 'https://images.unsplash.com/photo-1504384308090-c894fdcc538d?auto=format&fit=crop&w=800&q=80'}" 
          alt="${h.title}" 
          class="card-banner-img"
          loading="lazy"
          onerror="this.src='https://images.unsplash.com/photo-1504384308090-c894fdcc538d?auto=format&fit=crop&w=800&q=80'"
        />
        <span class="badge-mode ${modeClass}">${modeIcon}</span>
        <span class="badge-source">${h.source || 'Aggregated'}</span>
      </div>

      <div class="card-body">
        <h3 class="card-title" title="${h.title}">${h.title}</h3>
        <p class="card-organizer">by ${h.organizer || 'Indian Tech Community'}</p>

        <div class="card-address-box">
          <span class="address-icon">${addressIcon}</span>
          <span class="address-text" title="${h.venue_address || 'India'}">
            ${h.venue_address || 'Check official event link for venue details'}
          </span>
        </div>

        <div class="card-meta-row">
          <div class="prize-box">
            <span class="prize-lbl">Prize Pool</span>
            <span class="prize-val">${h.prize_pool || 'Prizes & Swag'}</span>
          </div>
          <div class="countdown-box">
            <span class="countdown-lbl">Deadline</span>
            <span class="countdown-val" style="color: ${isUrgent ? 'var(--accent-rose)' : 'var(--accent-emerald)'}">
              ${countdownText}
            </span>
          </div>
        </div>

        <div class="card-tags">
          ${tagsHtml}
        </div>

        <div class="card-actions">
          <a 
            href="${h.source_url}" 
            target="_blank" 
            rel="noopener noreferrer" 
            class="btn-apply"
          >
            Apply on ${h.source || 'Platform'} →
          </a>
          <button 
            class="btn-cal" 
            title="Add to Google Calendar"
            onclick="addToGoogleCalendar('${encodeURIComponent(h.title)}', '${encodeURIComponent(h.venue_address || '')}', '${h.deadline || ''}', '${encodeURIComponent(h.source_url)}')"
          >
            📅
          </button>
        </div>
      </div>
    `;

    container.appendChild(card);
  });
}

// --- Google Calendar Quick Link ---
window.addToGoogleCalendar = function(title, venue, deadline, url) {
  const eventTitle = decodeURIComponent(title);
  const eventDetails = `Registration deadline for ${eventTitle}.\nApply here: ${decodeURIComponent(url)}`;
  const location = decodeURIComponent(venue);
  
  let dateParam = '';
  if (deadline) {
    const d = new Date(deadline);
    const startStr = d.toISOString().replace(/-|:|\.\d\d\d/g, "");
    dateParam = `&dates=${startStr}/${startStr}`;
  }

  const gcalUrl = `https://calendar.google.com/calendar/render?action=TEMPLATE&text=${encodeURIComponent(eventTitle + ' - Deadline')}&details=${encodeURIComponent(eventDetails)}&location=${encodeURIComponent(location)}${dateParam}`;
  window.open(gcalUrl, '_blank');
};

// --- Event Listeners ---
function initEventListeners() {
  // Search Input with Debounce
  let searchTimeout;
  elements.searchInput.addEventListener('input', (e) => {
    clearTimeout(searchTimeout);
    elements.clearSearchBtn.style.display = e.target.value ? 'block' : 'none';
    searchTimeout = setTimeout(() => {
      state.filters.search = e.target.value;
      applyFilters();
    }, 200);
  });

  elements.clearSearchBtn.addEventListener('click', () => {
    elements.searchInput.value = '';
    elements.clearSearchBtn.style.display = 'none';
    state.filters.search = '';
    applyFilters();
  });

  // Mode Tabs
  elements.modeTabs.forEach(tab => {
    tab.addEventListener('click', () => {
      elements.modeTabs.forEach(t => t.classList.remove('active'));
      tab.classList.add('active');
      state.filters.mode = tab.dataset.mode;
      applyFilters();
    });
  });

  // City Dropdown
  elements.citySelect.addEventListener('change', (e) => {
    state.filters.city = e.target.value;
    applyFilters();
  });

  // Sort Dropdown
  elements.sortSelect.addEventListener('change', (e) => {
    state.filters.sort = e.target.value;
    applyFilters();
  });

  // Tag Pills
  elements.tagsContainer.addEventListener('click', (e) => {
    if (e.target.classList.contains('tag-pill')) {
      document.querySelectorAll('.tag-pill').forEach(p => p.classList.remove('active'));
      e.target.classList.add('active');
      state.filters.tag = e.target.dataset.tag;
      applyFilters();
    }
  });

  // Reset Button
  elements.resetFiltersBtn.addEventListener('click', resetAllFilters);

  // Submit Modal
  elements.openSubmitModalBtn.addEventListener('click', () => {
    elements.submitModal.classList.add('open');
  });

  const closeModal = () => elements.submitModal.classList.remove('open');
  elements.closeSubmitModalBtn.addEventListener('click', closeModal);
  elements.cancelSubmitModalBtn.addEventListener('click', closeModal);
  elements.submitModal.addEventListener('click', (e) => {
    if (e.target === elements.submitModal) closeModal();
  });

  // Handle Community Event Submission
  elements.submitEventForm.addEventListener('submit', (e) => {
    e.preventDefault();
    const newEvent = {
      source: "Community Submission",
      source_url: document.getElementById('eventUrl').value,
      title: document.getElementById('eventTitle').value,
      organizer: document.getElementById('eventOrganizer').value,
      mode: document.getElementById('eventMode').value,
      venue_address: document.getElementById('eventVenue').value,
      city: document.getElementById('eventMode').value === 'Online' ? 'Online' : document.getElementById('eventVenue').value.split(',')[0].trim(),
      banner_url: document.getElementById('eventBanner').value || 'https://images.unsplash.com/photo-1504384308090-c894fdcc538d?auto=format&fit=crop&w=800&q=80',
      deadline: document.getElementById('eventDeadline').value + 'T23:59:59Z',
      prize_pool: document.getElementById('eventPrize').value || 'TBA',
      tags: ["Student Hackathon", "Community"]
    };

    // Save to local storage for persistence across reloads
    const local = JSON.parse(localStorage.getItem('hackradar_user_submissions') || '[]');
    local.unshift(newEvent);
    localStorage.setItem('hackradar_user_submissions', JSON.stringify(local));

    state.hackathons.unshift(newEvent);
    updateMetrics();
    applyFilters();
    closeModal();
    elements.submitEventForm.reset();
    showToast(`🎉 "${newEvent.title}" submitted and added to your feed!`);
  });

  // Manual Sync Link
  elements.syncNowLink.addEventListener('click', (e) => {
    e.preventDefault();
    showToast("🔄 Re-syncing latest hackathon feeds...");
    loadHackathonData();
  });
}

function resetAllFilters() {
  state.filters.search = '';
  state.filters.mode = 'ALL';
  state.filters.city = 'ALL';
  state.filters.tag = 'ALL';
  state.filters.sort = 'deadline_asc';

  elements.searchInput.value = '';
  elements.clearSearchBtn.style.display = 'none';
  elements.citySelect.value = 'ALL';
  elements.sortSelect.value = 'deadline_asc';

  elements.modeTabs.forEach(t => t.classList.toggle('active', t.dataset.mode === 'ALL'));
  document.querySelectorAll('.tag-pill').forEach(p => p.classList.toggle('active', p.dataset.tag === 'ALL'));

  applyFilters();
}

function showToast(msg) {
  const t = elements.toast;
  t.textContent = msg;
  t.classList.add('show');
  setTimeout(() => {
    t.classList.remove('show');
  }, 3500);
}
