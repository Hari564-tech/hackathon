// --- Data Loading ---
async function loadHackathonData() {
  try {
    elements.loadingState.style.display = 'flex';
    elements.cardsGrid.innerHTML = '';
    elements.emptyState.style.display = 'none';

    // Fetch snapshot generated by the automated Python pipeline
    const response = await fetch('data/hackathons.json?t=' + Date.now());
    if (!response.ok) {
      throw new Error(`HTTP ${response.status}`);
    }

    const data = await response.json();
    state.hackathons = data.hackathons || [];
    state.lastSynced = data.last_synced_at;

    // Load any community-submitted items from localStorage
    const localSubmissions = JSON.parse(localStorage.getItem('hackradar_user_submissions') || '[]');
    if (localSubmissions.length > 0) {
      state.hackathons = [...localSubmissions, ...state.hackathons];
    }

    updateMetrics();
    applyFilters();

    if (state.lastSynced) {
      const syncDate = new Date(state.lastSynced);
      const timeStr = syncDate.toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' });
      elements.syncStatus.innerHTML = `<span class="sync-dot"></span><span class="sync-text">Synced today at ${timeStr}</span>`;
    }
  } catch (err) {
    console.warn('Fallback to embedded dataset due to fetch limitation:', err);
    useFallbackData();
  } finally {
    elements.loadingState.style.display = 'none';
  }
}

